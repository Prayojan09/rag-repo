logger = logging.getLogger(__name__)
_parsed_ingestion_details: ContextVar[tuple[ParsedDocument, list[str]] | None] = ContextVar(
    "parsed_ingestion_details", default=None
)


def extract_text(filename: str, content: bytes) -> list[TextSegment]:
    """Load a document through its selected format adapter into text segments."""
    parsed = get_loader(filename, content).load(filename, content)
    segments, removed_lines = normalize_segments_with_removed(parsed.to_segments())
    _parsed_ingestion_details.set((parsed, removed_lines))
    return segments


def _safe_ingestion_error(exc: Exception) -> str:
    source = getattr(exc, "source", None)
    status_code = getattr(exc, "status_code", None) or getattr(source, "status_code", None)
    if status_code == 403:
        return (
            "Qdrant denied collection access. Create the configured collection in Qdrant Cloud "
            "or grant this API key collection-management access, then retry."
        )
    if status_code == 401:
        return "Qdrant rejected its API key. Check QDRANT_API_KEY, then retry."
    if isinstance(
        exc, httpx.ConnectError | httpx.TimeoutException | TimeoutError | OSError
    ) or isinstance(source, httpx.ConnectError | httpx.TimeoutException | TimeoutError | OSError):
        return "Qdrant could not be reached. Check QDRANT_URL and network access, then retry."
    if source is not None:
        return (
            "Qdrant could not complete vector indexing. Check QDRANT_TIMEOUT_SECONDS "
            "and the Qdrant connection, then retry."
        )
    return "Document processing failed; check service logs and retry."


class DuplicateDocumentError(Exception):
    def __init__(self, document_id: str):
        self.document_id = document_id


def _safe_name(filename: str) -> str:
    safe = filename.replace("\\", "/").rsplit("/", 1)[-1].strip()
    if (
        not safe
        or len(safe) > 255
        or "\x00" in safe
        or any(ord(character) < 32 for character in safe)
    ):
        raise IngestionError("The filename is invalid")
    return safe


def _document_path(root: Path, storage_key: str) -> Path:
    # storage_key is generated by the service, never supplied by the client.
    return root / storage_key


def _store_file(root: Path, storage_key: str, content: bytes) -> Path:
    root.mkdir(parents=True, exist_ok=True)
    destination = _document_path(root, storage_key)
    temporary = destination.with_suffix(".tmp")
    try:
        with temporary.open("xb") as output:
            output.write(content)
        os.replace(temporary, destination)
    finally:
        temporary.unlink(missing_ok=True)
    return destination


def _process_document(
    db: Session, document: Document, content: bytes, chunk_size: int, chunk_overlap: int
) -> Document:
    started_at = time.perf_counter()
    _parsed_ingestion_details.set(None)
    segments = extract_text(document.filename, content)
    extracted_at = time.perf_counter()
    parsed_details = _parsed_ingestion_details.get()
    _parsed_ingestion_details.set(None)
    if parsed_details:
        parsed, removed_lines = parsed_details
    else:
        parsed = ParsedDocument(
            [
                Block(
                    "paragraph",
                    segment.text,
                    page_number=segment.page_number,
                    heading=segment.heading,
                )
                for segment in segments
            ],
            parser_used="unknown",
        )
        removed_lines = []
    document.structured_content = structure_document(segments)
    structured_at = time.perf_counter()
    chunks = chunk_segments(segments, chunk_size=chunk_size, overlap=chunk_overlap)
    chunked_at = time.perf_counter()
    if not chunks:
        raise IngestionError("No usable text chunks were produced")
    document.quality_report = build_quality_report(
        parsed,
        segments,
        chunks,
        filename=document.filename,
        removed_header_footer_lines=removed_lines,
    )
    try:
        save_quality_report(document.id, document.quality_report)
    except OSError as exc:
        logger.warning(
            "Unable to persist document quality report (error_type=%s)",
            type(exc).__name__,
            extra={"document_id": document.id},
        )
    db.query(DocumentChunk).filter(DocumentChunk.document_id == document.id).delete()
    chunk_records: list[DocumentChunk] = []
    for ordinal, chunk in enumerate(chunks):
        stable_id = str(
            uuid.uuid5(
                uuid.NAMESPACE_URL,
                f"{document.id}:{document.sha256}:{ordinal}:{chunk.text}",
            )
        )
        chunk_record = DocumentChunk(
            id=stable_id,
            document_id=document.id,
            ordinal=ordinal,
            text=chunk.text,
            embed_text=chunk.embed_text,
            section_path=list(chunk.section_path),
            token_count=chunk.token_count,
            page_number=chunk.page_number,
            heading=chunk.heading,
        )
        db.add(chunk_record)
        chunk_records.append(chunk_record)
    document.status = "indexing"
    document.error_message = None
    db.commit()
    db.refresh(document)
    DocumentIndexer(get_dense_vector_service()).index(
        document_id=document.id,
        tenant_id=document.tenant_id,
        filename=document.filename,
        version=document.version,
        chunks=chunk_records,
    )
    indexed_at = time.perf_counter()
    logger.info(
        "Document processing completed (pages_or_segments=%d chunks=%d extract_seconds=%.2f "
        "structure_seconds=%.2f chunk_seconds=%.2f index_seconds=%.2f total_seconds=%.2f)",
        len(segments),
        len(chunks),
        extracted_at - started_at,
        structured_at - extracted_at,
        chunked_at - structured_at,
        indexed_at - chunked_at,
        indexed_at - started_at,
        extra={"document_id": document.id},
    )
    document.status = "ready"
    db.commit()
    db.refresh(document)
    return document


def ingest_document(
    db: Session,
    filename: str,
    content: bytes,
    storage_root: Path,
    max_bytes: int,
    chunk_size: int,
    chunk_overlap: int,
    tenant_id: str = "default",
) -> Document:
    document, _ = _create_queued_document(db, filename, content, storage_root, max_bytes, tenant_id)
    return _run_ingestion(db, document, content, chunk_size, chunk_overlap)


def queue_document(
    db: Session,
    filename: str,
    content: bytes,
    storage_root: Path,
    max_bytes: int,
    tenant_id: str = "default",
) -> Document:
    """Validate, persist, and return immediately with ingestion still queued."""
    document, _ = _create_queued_document(db, filename, content, storage_root, max_bytes, tenant_id)
    return document


def _create_queued_document(
    db: Session,
    filename: str,
    content: bytes,
    storage_root: Path,
    max_bytes: int,
    tenant_id: str,
) -> tuple[Document, Path]:
    filename = _safe_name(filename)
    if len(content) > max_bytes:
        limit_mb = max_bytes / (1024 * 1024)
        limit_label = f"{limit_mb:g} MB"
        raise IngestionError(
            f"The selected file exceeds the {limit_label} upload limit. "
            "Please select a smaller file."
        )
    media_type = validate_file(filename, content)
    digest = hashlib.sha256(content).hexdigest()
    existing = db.scalar(
        select(Document).where(Document.sha256 == digest, Document.tenant_id == tenant_id)
    )
    if existing:
        raise DuplicateDocumentError(existing.id)

    current_version = db.scalar(
        select(func.max(Document.version)).where(
            Document.filename == filename, Document.tenant_id == tenant_id
        )
    )
    document_id = str(uuid.uuid4())
    storage_key = f"{document_id}{Path(filename).suffix.lower()}"
    path = _store_file(storage_root, storage_key, content)
    document = Document(
        id=document_id,
        tenant_id=tenant_id,
        filename=filename,
        media_type=media_type,
        sha256=digest,
        size_bytes=len(content),
        version=(current_version or 0) + 1,
        status="queued",
        storage_key=storage_key,
    )
    try:
        db.add(document)
        db.commit()
        db.refresh(document)
        return document, path
    except IntegrityError as exc:
        db.rollback()
        existing = db.scalar(
            select(Document).where(Document.sha256 == digest, Document.tenant_id == tenant_id)
        )
        path.unlink(missing_ok=True)
        if existing:
            raise DuplicateDocumentError(existing.id) from exc
        raise IngestionError("A document version conflict occurred; retry the upload") from exc
    except Exception:
        db.rollback()
        path.unlink(missing_ok=True)
        raise


def process_queued_document(
    document_id: str, storage_root: Path, chunk_size: int, chunk_overlap: int
) -> None:
    """Process one persisted upload in a background task using its own DB session."""
    db = SessionLocal()
    try:
        document = db.get(Document, document_id)
        if document is None or document.status != "queued":
            return
        path = _document_path(storage_root, document.storage_key)
        try:
            content = path.read_bytes()
        except OSError:
            document.status = "failed"
            document.error_message = "Stored source file is unavailable"
            db.commit()
            return
        if hashlib.sha256(content).hexdigest() != document.sha256:
            document.status = "failed"
            document.error_message = "Stored source file failed its integrity check"
            db.commit()
            return
        _run_ingestion(db, document, content, chunk_size, chunk_overlap)
    finally:
        db.close()


def _run_ingestion(
    db: Session, document: Document, content: bytes, chunk_size: int, chunk_overlap: int
) -> Document:
    try:
        return _process_document(db, document, content, chunk_size, chunk_overlap)
    except IngestionError as exc:
        db.rollback()
        failed = db.get(Document, document.id)
        if failed is None:
            raise
        logger.warning(
            "Document ingestion stopped (document_id=%s reason=%s)",
            document.id,
            str(exc)[:300],
            extra={"document_id": document.id, "error_type": type(exc).__name__},
        )
        failed.status = "failed"
        failed.error_message = str(exc)[:500]
        db.commit()
        return failed
    except Exception as exc:
        db.rollback()
        upstream_status = getattr(exc, "status_code", None)
        logger.exception(
            "Document ingestion failed (error_type=%s source_type=%s upstream_status=%s)",
            type(exc).__name__,
            type(getattr(exc, "source", None)).__name__ if getattr(exc, "source", None) else "none",
            upstream_status or "none",
            extra={
                "document_id": document.id,
                "error_type": type(exc).__name__,
                "upstream_status": upstream_status,
            },
        )
        failed = db.get(Document, document.id)
        if failed is None:
            raise
        failed.status = "failed"
        failed.error_message = _safe_ingestion_error(exc)
        db.commit()
        return failed


def retry_document(
    db: Session, document: Document, storage_root: Path, chunk_size: int, chunk_overlap: int
) -> Document:
    if document.status not in {"ready", "queued", "failed", "indexing"}:
        raise IngestionError("Only ready, queued, indexing, or failed documents can be retried")
    path = _document_path(storage_root, document.storage_key)
    try:
        content = path.read_bytes()
    except OSError as exc:
        raise IngestionError("Stored source file is unavailable") from exc
    if hashlib.sha256(content).hexdigest() != document.sha256:
        raise IngestionError("Stored source file failed its integrity check")
    document.status = "processing"
    document.retry_count += 1
    document.error_message = None
    db.commit()
    return _run_ingestion(db, document, content, chunk_size, chunk_overlap)


def delete_document(db: Session, document: Document, storage_root: Path) -> None:
    path = _document_path(storage_root, document.storage_key)
    document_id = document.id
    tenant_id = document.tenant_id
    db.delete(document)
    db.commit()
    delete_quality_report(document_id)
    try:
        get_dense_vector_service().delete_document(document_id, tenant_id)
    except Exception as exc:
        logger.error(
            "Unable to remove document vectors",
            extra={"document_id": document_id, "error_type": type(exc).__name__},
        )
    try:
        path.unlink(missing_ok=True)
    except OSError as exc:
        logger.error(
            "Unable to remove stored source file",
            extra={"document_id": document_id, "error_type": type(exc).__name__},
        )


def reindex_document(db: Session, document: Document) -> Document:
    if document.status != "ready":
        raise IngestionError("Only ready documents can be re-indexed")
    chunks = list(
        db.scalars(
            select(DocumentChunk)
            .where(DocumentChunk.document_id == document.id)
            .order_by(DocumentChunk.ordinal)
        ).all()
    )
    if not chunks:
        raise IngestionError("The document has no extracted chunks to index")
    document.status = "indexing"
    document.error_message = None
    db.commit()
    try:
        DocumentIndexer(get_dense_vector_service()).index(
            document_id=document.id,
            tenant_id=document.tenant_id,
            filename=document.filename,
            version=document.version,
            chunks=chunks,
        )
    except Exception as exc:
        db.rollback()
        failed = db.get(Document, document.id)
        if failed:
            failed.status = "failed"
            failed.error_message = "Vector indexing failed; retry document"
            db.commit()
        logger.error(
            "Document vector re-indexing failed",
            extra={"document_id": document.id, "error_type": type(exc).__name__},
        )
        raise IngestionError("Vector indexing failed; retry the document") from exc
    document.status = "ready"
    document.error_message = None
    db.commit()
    db.refresh(document)
    return document


def get_document(db: Session, document_id: str, tenant_id: str = "default") -> Document | None:
    return db.scalar(
        select(Document)
        .options(selectinload(Document.chunks))
        .where(Document.id == document_id, Document.tenant_id == tenant_id)
    )
